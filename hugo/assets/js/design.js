/* ==========================================================================
   Mockup 01 — "Typographic Index"

   Two levels, no page loads. The index stays put and a section slides over
   it; inside a section, an item slides over the section. Routing is all hash:

       #/              the index
       #/talks         the recordings list
       #/talks/teIK..  one recording, with its video and writeup

   so every level is linkable, the back button works, and a page can be opened
   cold from a URL. Content for the item level is fetched from details/<name>.html
   (generated by tools/build_content.py) and prefetched while the page is idle.
   ========================================================================== */
(function () {
  'use strict';

  var root = document.documentElement;
  var SECTIONS = ['bio', 'talks', 'blogs', 'tech', 'work', 'contact'];
  var WITH_ITEMS = ['talks', 'blogs', 'tech', 'work'];
  var LABELS = {
    bio: 'Bio',
    talks: 'Talks',
    blogs: 'Blogs',
    tech: 'Tech',
    work: 'Work',
    contact: 'Contact'
  };
  var BASE_TITLE = 'Graham Brooks — Index';
  var MERMAID_SRC = 'https://cdn.jsdelivr.net/npm/mermaid@11/dist/mermaid.min.js';

  var panels = {};
  Array.prototype.forEach.call(document.querySelectorAll('.panel'), function (panel) {
    panels[panel.dataset.section] = panel;
  });

  var active = null;          // section name, or null when the index is showing
  var activeItem = null;      // item slug inside the active section, or null
  var lastTrigger = null;     // what to give focus back to
  var lastItemTrigger = null;
  var loaded = {};            // section -> promise for its injected item pages
  var failed = {};            // section -> true once a fetch has failed

  /* ---------- helpers ---------- */

  function nextFrame(fn) {
    requestAnimationFrame(function () {
      requestAnimationFrame(fn);
    });
  }

  function scrollerOf(panel) {
    return panel.querySelector('[data-scroll]');
  }

  function subOf(panel) {
    return panel.querySelector('[data-sub]');
  }

  function subScrollerOf(panel) {
    return panel.querySelector('[data-subscroll]');
  }

  function setInert(el, isInert) {
    if (!el) { return; }
    if (isInert) {
      el.setAttribute('inert', '');
      el.setAttribute('aria-hidden', 'true');
    } else {
      el.removeAttribute('inert');
      el.setAttribute('aria-hidden', 'false');
    }
  }

  /* ---------- section level ---------- */

  function openSection(name, options) {
    var opts = options || {};
    var dir = opts.dir === undefined ? 1 : opts.dir;
    var animate = opts.animate !== false;
    var push = opts.push !== false;

    var next = panels[name];
    if (!next || name === active) { return; }

    // Leaving a section while one of its item pages is open: park that item
    // first, or coming back to the section would show the old item page with
    // the URL claiming the list.
    if (active && activeItem) { hideItem({ push: false, animate: false }); }

    if (active) {
      var prev = panels[active];
      prev.classList.remove('is-in');
      prev.classList.add(dir >= 0 ? 'is-leaving-left' : 'is-leaving-right');
      setInert(prev, true);
    }

    // Park the incoming panel where it should enter from.
    next.classList.remove('is-in', 'is-leaving-left', 'is-leaving-right');
    next.classList.add(dir >= 0 ? 'is-leaving-right' : 'is-leaving-left');

    var scroller = scrollerOf(next);
    if (scroller) { scroller.scrollTop = 0; }
    setInert(next, false);

    var paint = function () {
      next.classList.remove('is-leaving-left', 'is-leaving-right');
      next.classList.add('is-in');
      var title = next.querySelector('[tabindex="-1"]');
      if (title) { title.focus({ preventScroll: true }); }
    };

    if (animate) { nextFrame(paint); } else { paint(); }

    active = name;
    root.setAttribute('data-active', name);
    document.title = LABELS[name] ? 'Graham Brooks — ' + LABELS[name] : BASE_TITLE;
    setProgress(next, 0);

    if (push) {
      history.pushState({ section: name }, '', '#/' + name);
    }
  }

  function closeSection(options) {
    var opts = options || {};
    if (!active) { return; }

    var panel = panels[active];
    if (activeItem) { hideItem({ push: false, animate: false }); }

    panel.classList.remove('is-in', 'is-leaving-left');
    panel.classList.add('is-leaving-right');
    setInert(panel, true);

    if (lastTrigger && document.contains(lastTrigger)) {
      lastTrigger.focus({ preventScroll: true });
    }

    active = null;
    root.removeAttribute('data-active');
    document.title = BASE_TITLE;

    if (opts.push !== false) {
      history.pushState({ section: null }, '', location.pathname + location.search);
    }
  }

  /* ---------- item level: fetch the generated pages ---------- */

  function detailNote(panel, message) {
    var inner = panel.querySelector('[data-subinner]');
    if (!inner) { return; }
    inner.innerHTML = '<div class="detail detail--note"><p>' + message + '</p></div>';
  }

  function loadItems(section) {
    var panel = panels[section];
    if (!panel || WITH_ITEMS.indexOf(section) === -1) { return Promise.resolve(null); }
    if (loaded[section]) { return loaded[section]; }

    loaded[section] = fetch('details/' + section + '.html', { credentials: 'same-origin' })
      .then(function (response) {
        if (!response.ok) { throw new Error('HTTP ' + response.status); }
        return response.text();
      })
      .then(function (text) {
        var holder = document.createElement('div');
        holder.innerHTML = text;
        var inner = panel.querySelector('[data-subinner]');
        while (holder.firstChild) { inner.appendChild(holder.firstChild); }
        return inner;
      })
      .catch(function (error) {
        loaded[section] = null;
        failed[section] = true;
        detailNote(panel, 'This page could not load (' + error.message +
          '). <a href="" data-reload>Try again</a>.');
        return null;
      });
    return loaded[section];
  }

  function showItem(section, slug, options) {
    var opts = options || {};
    var panel = panels[section];
    if (!panel) { return; }

    loadItems(section).then(function (inner) {
      if (!inner) { return; }
      var view = inner.querySelector('.view--detail[data-slug="' + slug + '"]');
      if (!view) {
        detailNote(panel, 'No page for this one yet.');
        return;
      }

      var views = inner.querySelectorAll('.view--detail');
      Array.prototype.forEach.call(views, function (other) {
        other.hidden = other !== view;
      });

      var sub = subOf(panel);
      sub.hidden = false;
      panel.classList.add('has-item');
      setInert(panel.querySelector('.panel__bar'), true);
      setInert(scrollerOf(panel), true);

      var label = panel.querySelector('[data-subback-label]');
      if (label) { label.textContent = LABELS[section] || 'Back'; }
      var tag = panel.querySelector('[data-subtag]');
      if (tag) { tag.textContent = panel.dataset.index + ' / ' + (LABELS[section] || ''); }

      var subScroller = subScrollerOf(panel);
      if (subScroller) { subScroller.scrollTop = 0; }

      var paint = function () {
        sub.classList.add('is-in');
        var title = view.querySelector('.detail__title');
        if (title) { title.focus({ preventScroll: true }); }
        if (spies[section]) { spies[section](); }
        scheduleMermaid(view);
      };
      if (opts.animate === false) { paint(); } else { nextFrame(paint); }

      activeItem = slug;
      setSubProgress(panel, 0);
      if (opts.push !== false) {
        history.pushState({ section: section, item: slug }, '', '#/' + section + '/' + slug);
      }
    });
  }

  function hideItem(options) {
    var opts = options || {};
    if (!active || !activeItem) { return; }
    var panel = panels[active];
    var sub = subOf(panel);
    if (!sub) { return; }

    sub.classList.remove('is-in');
    panel.classList.remove('has-item');
    setInert(panel.querySelector('.panel__bar'), false);
    setInert(scrollerOf(panel), false);

    if (lastItemTrigger && document.contains(lastItemTrigger)) {
      lastItemTrigger.focus({ preventScroll: true });
    }

    var slug = activeItem;
    activeItem = null;

    var settle = function () {
      if (activeItem === slug || activeItem) { return; }
      if (sub.classList.contains('is-in')) { return; }
      sub.hidden = true;
      // park every view too, so nothing is left in a shown state behind a
      // hidden layer (and the next open starts from a clean slate)
      Array.prototype.forEach.call(sub.querySelectorAll('.view--detail'), function (view) {
        view.hidden = true;
      });
    };
    if (opts.animate === false) { settle(); } else { window.setTimeout(settle, 460); }

    if (opts.push !== false) {
      history.pushState({ section: active }, '', '#/' + active);
    }
  }

  /* ---------- video: nothing third-party until a click ---------- */

  function wirePlayer() {
    document.addEventListener('click', function (event) {
      var button = event.target.closest('.player__btn');
      if (!button) { return; }
      var figure = button.closest('.player');
      if (!figure) { return; }
      var video = document.createElement('video');
      video.controls = true;
      video.autoplay = true;
      video.playsInline = true;
      video.preload = 'metadata';
      video.poster = figure.dataset.poster || '';
      video.src = figure.dataset.video || '';
      figure.insertBefore(video, figure.firstChild);
      button.remove();
    });
  }

  /* ---------- mermaid, only where a diagram exists ----------
     The bundle is the live site's own vendored copy (same renderer, same look,
     no CDN), loaded the first time an item page actually contains a diagram. */

  var MERMAID_SRC = 'assets/mermaid.min.js';
  var D3_SRC = 'assets/d3.min.js';
  var mermaidPromise = null;

  function loadScript(src) {
    return new Promise(function (resolve, reject) {
      var script = document.createElement('script');
      script.src = src;
      script.onload = resolve;
      script.onerror = function () { reject(new Error(src + ' unavailable')); };
      document.head.appendChild(script);
    });
  }

  function ensureMermaid() {
    if (mermaidPromise) { return mermaidPromise; }
    mermaidPromise = loadScript(D3_SRC)
      .then(function () { return loadScript(MERMAID_SRC); })
      .catch(function () { return loadScript(MERMAID_SRC); })
      .then(function () {
        window.mermaid.initialize({
          startOnLoad: false,
          theme: 'neutral',
          securityLevel: 'loose',
          fontFamily: 'inherit',
          suppressErrors: true
        });
        return window.mermaid;
      });
    return mermaidPromise;
  }

  function renderMermaid(scope) {
    var nodes = scope.querySelectorAll('.mermaid:not([data-processed])');
    if (!nodes.length) { return; }
    var list = Array.prototype.slice.call(nodes);
    ensureMermaid().then(function (mermaid) {
      return mermaid.run({ nodes: list, suppressErrors: true });
    }).catch(function () { /* the diagram source stays readable */ });
  }

  /* Diagrams are drawn only after the item page has settled. Rendering during
     the slide (or worse, into a view that is hidden a moment later) makes
     mermaid measure a zero-size box and emit NaN transforms into the console;
     waiting is also when the user is actually looking at it. */
  var mermaidTimer = null;

  function scheduleMermaid(view) {
    window.clearTimeout(mermaidTimer);
    mermaidTimer = window.setTimeout(function () {
      if (view.hidden) { return; }
      var panel = view.closest('.panel');
      var sub = panel && subOf(panel);
      if (!sub || !sub.classList.contains('is-in')) { return; }
      renderMermaid(view);
    }, 520);
  }

  /* ---------- where am I in this piece ----------
     The wide layout puts the contents beside the body, so it should say which
     section you are in. Only headings that actually have an id are tracked, so
     a page without a contents list costs nothing. */

  var spies = {};

  function wireSpy(panel) {
    var scroller = subScrollerOf(panel);
    if (!scroller) { return; }

    function update() {
      var view = panel.querySelector('.view--detail:not([hidden])');
      if (!view) { return; }
      var rail = view.querySelector('.toc-rail');
      if (!rail || !rail.offsetParent) { return; }

      var headings = view.querySelectorAll('.prose h2[id], .prose h3[id]');
      if (!headings.length) { return; }
      var top = scroller.getBoundingClientRect().top + 80;
      var current = null;
      Array.prototype.forEach.call(headings, function (heading) {
        if (heading.getBoundingClientRect().top <= top) { current = heading.id; }
      });
      if (!current) { current = headings[0].id; }

      Array.prototype.forEach.call(rail.querySelectorAll('a'), function (link) {
        link.classList.toggle('is-current', link.getAttribute('href') === '#' + current);
      });
    }

    spies[panel.dataset.section] = update;

    var ticking = false;
    scroller.addEventListener('scroll', function () {
      if (ticking) { return; }
      ticking = true;
      requestAnimationFrame(function () { ticking = false; update(); });
    }, { passive: true });
  }

  /* ---------- progress rules ---------- */

  function setProgress(panel, ratio) {
    var bar = panel.querySelector('.panel__progress i');
    if (bar) { bar.style.transform = 'scaleX(' + ratio + ')'; }
  }

  function setSubProgress(panel, ratio) {
    var bar = panel.querySelector('.sub__progress i');
    if (bar) { bar.style.transform = 'scaleX(' + ratio + ')'; }
  }

  function wireScrollRule(scroller, apply) {
    if (!scroller) { return; }
    var ticking = false;
    scroller.addEventListener('scroll', function () {
      if (ticking) { return; }
      ticking = true;
      requestAnimationFrame(function () {
        ticking = false;
        var max = scroller.scrollHeight - scroller.clientHeight;
        apply(max > 4 ? Math.min(1, scroller.scrollTop / max) : 0);
      });
    }, { passive: true });
  }

  /* ---------- reveal on entry / on scroll ---------- */

  var revealObserver = null;

  function revealTargets(scope) {
    var targets = scope.querySelectorAll('[data-inview]');
    Array.prototype.forEach.call(targets, function (el) {
      if (revealObserver) { revealObserver.observe(el); } else { el.classList.add('is-visible'); }
    });
  }

  function wireReveals() {
    if (!('IntersectionObserver' in window)) { revealTargets(document); return; }
    revealObserver = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (!entry.isIntersecting) { return; }
        entry.target.classList.add('is-visible');
        revealObserver.unobserve(entry.target);
      });
    }, { rootMargin: '-4% 0px -10% 0px', threshold: 0.08 });
    revealTargets(document);
  }

  /* ---------- input ---------- */

  function routeFromHash() {
    var match = (location.hash || '').match(/^#\/([a-z]+)(?:\/([A-Za-z0-9_-]+))?$/);
    if (!match || !panels[match[1]]) { return { section: null, item: null }; }
    return { section: match[1], item: match[2] || null };
  }

  function openItemFrom(link) {
    var match = (link.getAttribute('href') || '').match(/^#\/([a-z]+)\/([A-Za-z0-9_-]+)$/);
    if (!match) { return false; }
    var name = match[1];
    if (!panels[name]) { return false; }
    lastItemTrigger = link;
    if (name !== active) {
      var from = active ? SECTIONS.indexOf(active) : -1;
      openSection(name, { dir: from >= 0 && SECTIONS.indexOf(name) < from ? -1 : 1, push: false });
    }
    showItem(name, match[2]);
    return true;
  }

  function wireLinks() {
    document.addEventListener('click', function (event) {
      var reload = event.target.closest('[data-reload]');
      if (reload) {
        event.preventDefault();
        if (active) { loadItems(active); }
        return;
      }

      var back = event.target.closest('[data-subback]');
      if (back) {
        event.preventDefault();
        hideItem();
        return;
      }

      var closer = event.target.closest('[data-close]');
      if (closer) {
        event.preventDefault();
        closeSection();
        return;
      }

      var itemLink = event.target.closest('a[href^="#/"]');
      if (itemLink && openItemFrom(itemLink)) {
        event.preventDefault();
        return;
      }

      // A contents or footnote link inside a page: scroll to it, but leave the
      // route hash alone. Letting the browser follow it would rewrite the URL
      // to "#introduction" and the router would close the section.
      var anchor = event.target.closest('a[href^="#"]:not([href^="#/"])');
      if (anchor) {
        var id = (anchor.getAttribute('href') || '').slice(1);
        var target = id && document.getElementById(id);
        if (target) {
          event.preventDefault();
          target.scrollIntoView({
            block: 'start',
            behavior: window.matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth'
          });
          return;
        }
      }

      var link = event.target.closest('a[data-section]');
      if (!link) { return; }
      var name = link.dataset.section;
      if (!panels[name]) { return; }
      event.preventDefault();
      if (name === active) { return; }
      lastTrigger = link;
      var from = active ? SECTIONS.indexOf(active) : -1;
      openSection(name, { dir: from >= 0 && SECTIONS.indexOf(name) < from ? -1 : 1 });
    });
  }

  function wireKeys() {
    document.addEventListener('keydown', function (event) {
      if (!active || event.metaKey || event.ctrlKey || event.altKey) { return; }
      var tag = (event.target.tagName || '').toLowerCase();
      if (tag === 'input' || tag === 'textarea' || event.target.isContentEditable) { return; }
      if (event.key === 'Escape' || event.key === 'ArrowLeft') {
        event.preventDefault();
        if (activeItem) { hideItem(); } else { closeSection(); }
      }
    });
  }

  function wireSwipe() {
    var start = null;
    Array.prototype.forEach.call(document.querySelectorAll('.panel'), function (panel) {
      panel.addEventListener('pointerdown', function (event) {
        if (event.pointerType === 'mouse') { return; }
        start = { x: event.clientX, y: event.clientY, id: event.pointerId };
      });
      panel.addEventListener('pointerup', function (event) {
        if (!start || event.pointerId !== start.id) { return; }
        var dx = event.clientX - start.x;
        var dy = event.clientY - start.y;
        start = null;
        if (Math.abs(dy) > 70 || Math.abs(dx) < 90) { return; }
        if (dx > 0) {
          if (activeItem) { hideItem(); } else { closeSection(); }
          return;
        }
        if (activeItem) { return; }
        var at = SECTIONS.indexOf(active);
        if (at > -1 && at < SECTIONS.length - 1) {
          openSection(SECTIONS[at + 1], { dir: 1 });
        }
      });
      panel.addEventListener('pointercancel', function () { start = null; });
    });
  }

  /* Both of these land on the same place, and both have to be wired: the back
     button fires popstate, but a hand-edited URL or an anchor that only changes
     the hash fires hashchange instead. pushState (our own navigation) fires
     neither, so there is nothing to de-duplicate. */
  function applyRoute() {
    var route = routeFromHash();
    if (!route.section) {
      // A fragment we do not route, with a section open: something (a stray
      // anchor, a hand-edited URL) changed the hash. Put the route back rather
      // than throwing the reader out of the page. An empty hash is not a
      // stray fragment though -- that is the way back to the index.
      var hash = location.hash;
      if (active && hash && hash !== '#') {
        history.replaceState(null, '', '#/' + active + (activeItem ? '/' + activeItem : ''));
        return;
      }
      closeSection({ push: false });
      return;
    }

    if (route.section !== active) {
      var from = active ? SECTIONS.indexOf(active) : -1;
      openSection(route.section, {
        push: false,
        dir: from >= 0 && SECTIONS.indexOf(route.section) < from ? -1 : 1
      });
    }
    if (route.item && route.item !== activeItem) {
      showItem(route.section, route.item, { push: false, animate: false });
    } else if (!route.item && activeItem) {
      hideItem({ push: false });
    }
  }

  function wireHistory() {
    window.addEventListener('popstate', applyRoute);
    window.addEventListener('hashchange', applyRoute);
  }

  function wireGalleryLink() {
    // The gallery lives on the bare hostname (no variant port / path).
    Array.prototype.forEach.call(document.querySelectorAll('[data-gallery]'), function (link) {
      link.href = location.protocol + '//' + location.hostname + '/';
    });
  }

  /* ---------- word cloud ----------
     The stagger delay rides an animation (see mockup.css), so the index only
     has to be published as a custom property. Hover brings a cluster forward:
     colour only, and only where a real pointer exists. */
  function wireCloud() {
    var cloud = document.querySelector('.cloud');
    if (!cloud) { return; }

    var words = Array.prototype.slice.call(cloud.querySelectorAll('.cloud__w'));
    words.forEach(function (word, i) { word.style.setProperty('--i', i); });

    if (!window.matchMedia('(hover: hover)').matches) { return; }

    function clear() {
      words.forEach(function (word) { word.classList.remove('is-hot', 'is-dim'); });
    }

    words.forEach(function (word) {
      word.addEventListener('pointerenter', function () {
        var cluster = word.dataset.cluster;
        words.forEach(function (other) {
          var same = other.dataset.cluster === cluster;
          other.classList.toggle('is-hot', same);
          other.classList.toggle('is-dim', !same);
        });
      });
      word.addEventListener('pointerleave', clear);
      word.addEventListener('pointercancel', clear);
    });
  }

  /* ---------- prefetch, once the page is idle ---------- */

  function prefetch() {
    var queue = WITH_ITEMS.slice();
    function next() {
      var section = queue.shift();
      if (!section) { return; }
      loadItems(section).then(function () {
        window.setTimeout(next, 120);
      });
    }
    next();
  }

  /* ---------- init ---------- */

  Array.prototype.forEach.call(document.querySelectorAll('.panel'), function (panel) {
    wireScrollRule(scrollerOf(panel), function (ratio) { setProgress(panel, ratio); });
    wireScrollRule(subScrollerOf(panel), function (ratio) { setSubProgress(panel, ratio); });
    wireSpy(panel);
  });
  wireReveals();
  wireCloud();
  wireLinks();
  wireKeys();
  wireSwipe();
  wireHistory();
  wireGalleryLink();
  wirePlayer();

  var initial = routeFromHash();
  if (initial.section) {
    history.replaceState({ section: initial.section, item: initial.item },
      '', location.hash);
    openSection(initial.section, { animate: false, push: false });
    if (initial.item) {
      showItem(initial.section, initial.item, { push: false, animate: false });
    }
    lastTrigger = null;
  }

  if ('requestIdleCallback' in window) {
    requestIdleCallback(prefetch, { timeout: 2500 });
  } else {
    window.setTimeout(prefetch, 1200);
  }
})();
